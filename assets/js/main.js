/* =====================================================
   ЗАБРАНА НА ДЕСЕН БУТОН (CONTEXT MENU)
   ===================================================== */

// Добавя слушател за събитието 'contextmenu' (десен клик) върху целия документ


// Намира специфична зона (изскачащия прозорец), ако искаме защитата да е по-строга там
const protectedArea = document.getElementById('popup-window');

// Ако тази зона съществува в HTML:
if (protectedArea) {
  protectedArea.addEventListener('contextmenu', (e) => {
    e.preventDefault(); // Повторна забрана специално за този елемент (за сигурност)
  });
}


/* =====================================================
   ЗАБРАНА НА КОПИРАНЕ
   ===================================================== */

// Добавя слушател за събитието 'copy' (Копиране)
document.addEventListener('copy', (e) => {
  e.preventDefault(); // Предотвратява записването на маркирания текст в клипборда на потребителя
});


/* =====================================================
   ЗАБРАНА НА КЛАВИШНИ КОМБИНАЦИИ
   ===================================================== */

// Добавя слушател за натискане на клавиш (keydown)
document.addEventListener('keydown', (e) => {

  // Списък със забранени букви (C за копиране, U за изходен код, S за запазване на страницата)
  const blockedKeys = ['c', 'u', 's'];

  /* Проверка за натиснати комбинации:
     1. Ctrl + C (Копиране)
     2. Ctrl + U (Виж изходния код на страницата)
     3. Ctrl + S (Запази страницата на компютъра)
     4. F12 (Отваряне на Developer Tools)
  */
  if (
    (e.ctrlKey && blockedKeys.includes(e.key.toLowerCase())) || // Ако е натиснат Ctrl + някоя от буквите
    e.key === 'F12' // Или ако е натиснат функционалният клавиш F12
  ) {
    e.preventDefault(); // Спира изпълнението на командата от браузъра
  }

});
/* =====================================================
   Logo → Back to top (Връщане в началото)
   ===================================================== */
document.addEventListener("DOMContentLoaded", () => {
  const logo = document.getElementById("center-logo"); // Намира централното лого

  if (!logo) return; // Ако го няма, спира изпълнението

  logo.style.cursor = "pointer"; // Променя курсора на ръчичка, за да подскаже, че се клика
  logo.addEventListener("click", () => {
    // Плавно превъртане на страницата до най-горната точка (Y=0)
    window.scrollTo({
      top: 0,
      behavior: "smooth" // "smooth" прави движението плавно, а не рязко
    });
  });
});